"""Pack the reviewed portrait GPT Image credits page for the 9588 LCD."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/credits'


def main():
    master_path = ASSETS / 'credits-gpt-image-master.png'
    master = Image.open(master_path).convert('L')
    target = master.resize((240,320),Image.Resampling.LANCZOS)
    target = target.point([min(3,(v+42)//85)*85 for v in range(256)])
    target.save(ASSETS/'credits-240x320.png')
    pixels=target.tobytes()
    packed=bytearray(struct.pack('<HHBB',240,320,1,32))
    for index in range(0,len(pixels),4):
        packed.append(sum((3-pixels[index+i]//85)<<(6-i*2) for i in range(4)))
    (ASSETS/'credits-240x320.bin').write_bytes(packed)
    text='/* GPT Image portrait credits; generated by tools/pack_credits.py. */\n'
    text+='\n'.join('  '+','.join(f'0x{v:02x}' for v in packed[i:i+16])+',' for i in range(0,len(packed),16))+'\n'
    (ROOT/'include/sango_credits_bitmap.inc').write_text(text,encoding='ascii')
    sha=lambda b:hashlib.sha256(b).hexdigest()
    metadata={'generator':'built-in image_gen (GPT Image)',
        'references':['credits-9588-reference.png','credits-9288s-reference.png'],
        'prompt':'imagegen-prompt.txt','master':master_path.name,
        'master_size':list(master.size),'master_sha256':sha(master_path.read_bytes()),
        'target':'credits-240x320.png','target_size':[240,320],
        'target_sha256':sha((ASSETS/'credits-240x320.png').read_bytes()),
        'packed_bytes':len(packed),'packed_sha256':sha(packed),'levels':[0,85,170,255],
        'display_rectangle':[0,0,240,320],
        'credits':['制作群组','策划','BBK gamegroup','程序','通宵虫','南方小凯','美工','Sunday']}
    (ASSETS/'provenance.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(metadata,ensure_ascii=False))


if __name__=='__main__':main()
