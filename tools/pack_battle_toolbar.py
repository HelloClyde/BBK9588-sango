"""Pack the reviewed GPT Image battle toolbar for the 9588 LCD."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import struct
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/battle-toolbar'


def main():
    master_path=ASSETS/'toolbar-gpt-image-master.png'
    master=Image.open(master_path).convert('L')
    if master.size!=(2172,724):raise ValueError('Review crop for changed master dimensions')
    # Reuse the reviewed Information/Find master, matching the 9288S labels.
    crop=(0,203,2172,521)
    target=master.crop(crop).resize((240,36),Image.Resampling.LANCZOS)
    target=target.point([min(3,(v+42)//85)*85 for v in range(256)])
    target.save(ASSETS/'toolbar-240x36.png')
    pixels=target.tobytes();raw=bytearray(struct.pack('<HHBB',240,36,1,32))
    for offset in range(0,len(pixels),4):raw.append(sum((3-pixels[offset+i]//85)<<(6-i*2) for i in range(4)))
    (ASSETS/'toolbar-240x36.bin').write_bytes(raw)
    text='/* GPT Image battle toolbar; generated by tools/pack_battle_toolbar.py. */\n'
    text+='\n'.join('  '+','.join(f'0x{v:02x}' for v in raw[i:i+16])+',' for i in range(0,len(raw),16))+'\n'
    (ROOT/'include/sango_battle_toolbar_bitmap.inc').write_text(text,encoding='ascii')
    sha=lambda b:hashlib.sha256(b).hexdigest()
    report={'generator':'built-in image_gen (GPT Image)','prompt':'imagegen-prompt.txt',
      'edit_reference':'toolbar-9288s-reference.png','reused_from':'../statusbar/toolbar-gpt-image-master.png',
      'master':master_path.name,'master_size':list(master.size),'master_sha256':sha(master_path.read_bytes()),
      'crop_box':list(crop),'target':'toolbar-240x36.png','target_size':[240,36],
      'target_sha256':sha((ASSETS/'toolbar-240x36.png').read_bytes()),
      'packed_sha256':sha(raw),'packed_bytes':len(raw),'display_rectangle':[0,248,240,36],
      'runtime_sampling':'None: full 240x36 source drawn at native size. Display viewport 240x224; summary uses y=284..319.',
      'text':['信息','查找'],'levels':[0,85,170,255]}
    (ASSETS/'provenance.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False))


if __name__=='__main__':main()
