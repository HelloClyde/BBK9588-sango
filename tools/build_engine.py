"""Generate the engine unity unit in the verified original definition order.

The editable sources live in functional modules. Compiling them together keeps
the existing cross-function optimization and fixed-address image layout stable.
The generated file is build output, not the source developers should edit.
"""
import json
import subprocess
from pathlib import Path
from .source_map import parse_functions

ROOT=Path(__file__).resolve().parents[1]

def write_unity(output):
    mapping=json.loads((ROOT/'source-map.json').read_text(encoding='utf-8'))
    lines=['/* Generated by tools/build_engine.py; edit the functional src modules. */']
    actual=[]
    for module in mapping['modules']:
        path=ROOT/module['file']
        if not path.is_file() or not path.resolve().is_relative_to((ROOT/'src').resolve()):
            raise ValueError('Invalid engine module: '+module['file'])
        actual.extend(parse_functions(path))
        lines.append('#include "../'+module['file']+'"')
    if actual!=[row['name'] for row in mapping['functions']]:
        raise ValueError('Module definitions/order differ from source-map.json; update the map and revalidate')
    output.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')

def add_legacy_debug_symbols(cc,elf):
    """Old names are ELF-only aliases for existing regression/debug tools."""
    mapping=json.loads((ROOT/'source-map.json').read_text(encoding='utf-8'))
    nm=cc.with_name(cc.name.replace('gcc','nm'))
    symbols={}
    for line in subprocess.check_output([str(nm),'-P','--defined-only',str(elf)],text=True).splitlines():
        fields=line.split()
        if len(fields)>=3:
            try:symbols[fields[0]]=int(fields[2],16)
            except ValueError:pass
    options=[];aliases=[]
    for row in mapping['functions']:
        old,new=row['legacy_name'],row['name']
        if old!=new and new in symbols:
            # This MIPS objcopy parses absolute values through a signed 32-bit
            # conversion. Section-relative offsets avoid saturating high KSEG
            # addresses, while the ELF symbol still resolves to the true VMA.
            text_base=0x81c00060
            if not text_base<=symbols[new]<0x81c1fef0:
                raise ValueError('Legacy function alias is outside .text: '+new)
            options.extend(['--add-symbol',f'{old}=.text:{symbols[new]-text_base:#x},global,function'])
            aliases.append({'legacy_name':old,'name':new,'address':symbols[new]})
    if options:
        response=elf.parent/'legacy-symbols.args'
        response.write_text('\n'.join(options)+'\n',encoding='ascii',newline='\n')
        objcopy=cc.with_name(cc.name.replace('gcc','objcopy'))
        subprocess.run([str(objcopy),'@'+str(response),str(elf)],check=True)
    (elf.parent/'legacy-symbols.json').write_text(json.dumps(aliases,indent=2)+'\n',encoding='utf-8',newline='\n')
